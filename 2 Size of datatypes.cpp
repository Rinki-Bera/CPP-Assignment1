#include<iostream>
using namespace std;
int main()
{
	int a;
	float b;
	char c;
	double d;
	long e;
	bool f;
	cout<<"Size of int:"<<sizeof(a)<<"bytes\n";
	cout<<"Size of float:"<<sizeof(b)<<"bytes\n";
	cout<<"Size of char:"<<sizeof(c)<<"bytes\n";
	cout<<"Size of double:"<<sizeof(d)<<"bytes\n";
	cout<<"Size of long:"<<sizeof(e)<<"bytes\n";
	cout<<"Size of bool:"<<sizeof(f)<<"bytes\n";
	return 0;
}
